"""Draw city/district maps. Cache DataV {code}_full.json in .cache/atlas-geo/districts."""
from collections import defaultdict
from concurrent.futures import ThreadPoolExecutor
import json
import math
import sys
from urllib.error import HTTPError
from urllib.request import urlopen
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "miniprogram/assets"
PACKAGE = ASSETS.parent / "pages/atlas-explore"
TARGET = PACKAGE / "district-maps"
DISTRICTS = ROOT / ".cache/atlas-geo/districts"
TARGET.mkdir(exist_ok=True)
cities = defaultdict(list)
for area in json.loads((ROOT / "server/app/data/city_boundaries.json").read_text()):
    cities[area["cityCode"]].extend(area["polygons"])


def cache_districts(code):
    target = DISTRICTS / f"{code}.json"
    if target.exists():
        return
    province_cache = DISTRICTS.parent / target.name
    if province_cache.exists():
        target.write_bytes(province_cache.read_bytes())
        return
    try:
        with urlopen(f"https://geo.datav.aliyun.com/areas_v3/bound/{code}_full.json", timeout=12) as response:
            data = response.read()
        if json.loads(data).get("features"):
            target.write_bytes(data)
    except HTTPError as error:
        if error.code != 404:
            raise


if "--fetch" in sys.argv:
    DISTRICTS.mkdir(parents=True, exist_ok=True)
    with ThreadPoolExecutor(max_workers=12) as pool:
        list(pool.map(cache_districts, sorted(cities)))


def project(lng, lat):
    return (
        416.3695106850359 * math.radians(lng) - 457.9428915814261,
        474.7017167958825
        - 416.3695106850359 * math.log(math.tan(math.pi / 4 + math.radians(lat) / 2)),
    )


frames = {}
for code, polygons in sorted(cities.items()):
    polygons = [[list(map(lambda p: project(*p), ring)) for ring in poly] for poly in polygons]
    points = [p for poly in polygons for p in poly[0]]
    xs, ys = zip(*points)
    x, y = (min(xs) + max(xs)) / 2, (min(ys) + max(ys)) / 2
    zoom = min(540 / max(max(xs) - min(xs), .001), 405 / max(max(ys) - min(ys), .001))
    frames[code] = {"frame": [round(n, 8) for n in (x, y, zoom)], "labels": []}
    width, height = 600, 465
    image = Image.new("P", (width, height))
    image.putpalette([0, 0, 0, 200, 215, 187, 139, 162, 131, 167, 186, 155])
    draw = ImageDraw.Draw(image)

    def pixels(ring):
        return [
            ((300 + (px - x) * zoom) * width / 600,
             (232.5 + (py - y) * zoom) * height / 465)
            for px, py in ring
        ]

    for outer, *holes in polygons:
        draw.polygon(pixels(outer), fill=1, outline=2)
        for hole in holes:
            draw.polygon(pixels(hole), fill=0, outline=2)
    source = DISTRICTS / f"{code}.json"
    if source.exists():
        for feature in json.loads(source.read_text())["features"]:
            geom = feature.get("geometry")
            props = feature["properties"]
            if not geom or str(props.get("adcode")) == code:
                continue
            rings = geom["coordinates"]
            if geom["type"] == "Polygon":
                rings = [rings]
            elif geom["type"] != "MultiPolygon":
                continue
            for polygon in rings:
                for ring in polygon:
                    path = pixels([project(*p[:2]) for p in ring])
                    draw.line(path, fill=3, width=1)
            center = props.get("centroid") or props.get("center")
            if center and props.get("name") and props.get("adcode"):
                frames[code]["labels"].append({
                    "name": props["name"],
                    "point": [round(n, 5) for n in project(*center[:2])],
                })
    image.save(TARGET / f"{code}.png", transparency=0, bits=2, optimize=True)

(PACKAGE / "district-maps.js").write_text(
    "// Generated by scripts/build_atlas_city_outlines.py\nmodule.exports = "
    + json.dumps(frames, separators=(",", ":")) + "\n"
)
