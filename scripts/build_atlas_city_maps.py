"""Build city/district boundary previews from DataV. Cached inputs can be reused offline."""
import json, math, subprocess, urllib.request
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
from PIL import Image, ImageDraw
ROOT=Path(__file__).resolve().parents[1]
ASSETS=ROOT/'miniprogram/assets'
CACHE=ROOT/'.cache/atlas-geo'
CACHE.mkdir(parents=True,exist_ok=True)
provinces=json.loads(subprocess.check_output(['node','-e',"process.stdout.write(JSON.stringify(require('./miniprogram/assets/atlas-provinces')))"],cwd=ROOT,text=True))
def project(p):
    lng,lat=p[:2]
    return [416.3695106850359*lng*math.pi/180-457.9428915814261,474.7017167958825-416.3695106850359*math.log(math.tan(math.pi/4+lat*math.pi/360))]
def build(province):
    code=province['code']
    if not isinstance(code,int): return None
    cache=CACHE/f'{code}.json'
    try:
        if not cache.exists():
            with urllib.request.urlopen(f'https://geo.datav.aliyun.com/areas_v3/bound/{code}_full.json',timeout=20) as response: cache.write_bytes(response.read())
        source=json.loads(cache.read_text())
        boxes=[]
        for polygon in province['polygons']:
            xs,ys=zip(*polygon[0]); boxes.append((min(xs),min(ys),max(xs)-min(xs),max(ys)-min(ys)))
        x,y,w,h=max(boxes,key=lambda b:b[2]*b[3]); zoom=min(40,540/max(w,1),405/max(h,1)); tx,ty=300-(x+w/2)*zoom,232.5-(y+h/2)*zoom
        image=Image.new('RGBA',(1200,930)); draw=ImageDraw.Draw(image); labels=[]
        for f in source['features']:
            g=f.get('geometry'); props=f['properties']
            if not g or g['type'] not in ['Polygon','MultiPolygon']: continue
            polygons=[g['coordinates']] if g['type']=='Polygon' else g['coordinates']
            for polygon in polygons:
                for ring in polygon:
                    pts=[((project(p)[0]*zoom+tx)*2,(project(p)[1]*zoom+ty)*2) for p in ring]
                    draw.polygon(pts,fill='#c6d5ba');draw.line(pts+[pts[0]],fill='#789274',width=1)
            center=props.get('centroid') or props.get('center')
            if center: labels.append({'name':props['name'],'point':project(center)})
        image.quantize(colors=64).save(ASSETS/'atlas-maps'/f'{code}-cities.png',optimize=True)
        return str(code),labels
    except Exception as e:
        print(f'{code}: {type(e).__name__}'); return None
with ThreadPoolExecutor(max_workers=8) as pool: result=dict(r for r in pool.map(build,provinces) if r)
(ASSETS/'atlas-cities.js').write_text('// DataV municipal/district centroids; generated by scripts/build_atlas_city_maps.py\nmodule.exports = '+json.dumps(result,ensure_ascii=False,separators=(',',':'))+'\n')
print('Built city boundaries for',len(result),'regions')
